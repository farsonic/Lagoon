#!/usr/bin/env python3
# Lagoon - locale catalog tool (a small FlexCat/CatComp replacement).
#
#   mkcatalog.py header CD OUT.h              C header: enum + English strings
#   mkcatalog.py catalog CD CT OUT.catalog    IFF CTLG catalog for locale.library
#   mkcatalog.py check CD CT...               every .ct complete, same %-formats
#
# .cd: "NAME (id/min/max)" then the string; ';' lines are comments; ids are
# sequential when empty. .ct: "## language x", "## version $VER: ...",
# "## codeset 0", then "NAME" and the translation. Sources are UTF-8; strings
# are stored in ISO-8859-1 (the Amiga character set). C escapes (\n, \t, \\,
# \") are understood.
# SPDX-License-Identifier: GPL-2.0-only
import re
import struct
import sys


def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "t": "\t", "\\": "\\", '"': '"', "e": "\x1b", "a": "\x07"}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def read_cd(path):
    entries, nid = [], 0
    lines = open(path, encoding="utf-8").read().split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        i += 1
        if not ln.strip() or ln.startswith(";") or ln.startswith("#"):
            continue
        m = re.match(r"^(\w+)\s*\((\d*)/(\d*)/(\d*)\)\s*$", ln)
        if not m:
            raise SystemExit("%s: bad line %r" % (path, ln))
        if m.group(2):
            nid = int(m.group(2))
        text = lines[i]
        i += 1
        entries.append((m.group(1), nid, unescape(text)))
        nid += 1
    return entries


def read_ct(path):
    meta, strings = {}, {}
    lines = open(path, encoding="utf-8").read().split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        i += 1
        if ln.startswith("##"):
            k, _, v = ln[2:].strip().partition(" ")
            meta[k] = v.strip()
            continue
        if not ln.strip() or ln.startswith(";"):
            continue
        name = ln.strip()
        strings[name] = unescape(lines[i]) if i < len(lines) else ""
        i += 1
    return meta, strings


def cstr(s):
    out = ""
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out += "\\\\"
        elif ch == '"':
            out += '\\"'
        elif ch == "\n":
            out += "\\n"
        elif o < 32 or o > 126:
            out += "\\%03o" % (ch.encode("latin-1")[0])
        else:
            out += ch
    return '"' + out + '"'


def header(cd, out):
    e = read_cd(cd)
    with open(out, "w", encoding="ascii") as f:
        f.write("/* Lagoon - LagoonPrefs strings, generated by tools/mkcatalog.py from\n")
        f.write(" * src/amiga/prefs/catalogs/LagoonPrefs.cd: do not edit.\n")
        f.write(" * SPDX-License-Identifier: GPL-2.0-only */\n")
        f.write("#ifndef LP_STRINGS_H\n#define LP_STRINGS_H\n\nenum {\n")
        for name, nid, _ in e:
            f.write("\t%s = %d,\n" % (name, nid))
        f.write("\tMSG_COUNT = %d\n};\n\n" % (e[-1][1] + 1))
        f.write("#ifdef LP_STRINGS_ARRAY\nstatic const char *const lp_builtin[MSG_COUNT] = {\n")
        byid = {nid: text for _, nid, text in e}
        for k in range(e[-1][1] + 1):
            f.write("\t%s,\n" % cstr(byid.get(k, "")))
        f.write("};\n#endif\n\n#endif\n")


def fmts(s):
    return re.findall(r"%[-0-9.]*l*[sdiuxc]", s)


def keys(s):
    i = s.find("_")
    return s[i + 1].lower() if i >= 0 and i + 1 < len(s) else None


