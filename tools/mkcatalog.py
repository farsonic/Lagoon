def check_keys(where, st):
    bad = 0
    for g in KEYGROUPS:
        seen = {}
        for name in g.split():
            k = keys(st.get(name, ""))
            if k and k in seen:
                print("%s: shortcut '%s' of %s is also %s's" % (where, k, name, seen[k]))
                bad += 1
            elif k:
                seen[k] = name
    return bad


def width8(s):
    return 8 * len(s.replace("_", ""))


def check_layout(where, st):
    """topaz 8 estimate of the main and editor window widths (the same
    arithmetic as lagoonprefs.c and editor.c): must fit a 640 pixel screen"""
    g = lambda n: st.get(n, "")
    row1 = sum(width8(g(n)) + 16 + 6 for n in ("MSG_ADD", "MSG_EDIT", "MSG_REMOVE", "MSG_BROWSE"))
    row1 += max(width8(g("MSG_MOUNT")), width8(g("MSG_UNMOUNT"))) + 16 + 6
    main_w = max(64 * 8 + 24, row1) + 16
    left = ("MSG_PROTOCOL MSG_SERVER MSG_SHARE_SMB MSG_SHARE_AFP MSG_SHARE_NFS MSG_FOLDER MSG_USER "
            "MSG_PASSWORD MSG_DOMAIN MSG_URL").split()
    lw1 = max(width8(g(n)) for n in left) + 16
    fw1 = max(max(width8(g(n)) for n in ("MSG_PROTO_SMB", "MSG_PROTO_AFP", "MSG_PROTO_NFS")) + 40, 26 * 8)
    lw2 = max(width8(g(n)) for n in ("MSG_DEVICE", "MSG_VOLLABEL", "MSG_UID", "MSG_GID")) + 16
    cbw = 26 + 8 + max(width8(g(n)) for n in ("MSG_AUTOMOUNT", "MSG_READONLY", "MSG_SIGN", "MSG_ENCRYPT",
                                               "MSG_CLEARTEXT"))
    ed_w = 8 + lw1 + fw1 + 16 + max(lw2 + 12 * 8, cbw) + 8
    # Sharing window: the list or the button row with "Start at boot"
    srow = sum(width8(g(n)) + 16 + 6 for n in ("MSG_ADD", "MSG_EDIT", "MSG_REMOVE", "MSG_USERS_BTN"))
    srow += 26 + 8 + width8(g("MSG_AUTOSTART"))
    sh_w = max(64 * 8 + 24, srow) + 16
    sname = width8(g("MSG_SRV_NAME")) + 16 + 16 * 8 + 16 + width8(g("MSG_SRV_GROUP")) + 16 + 16 * 8
    sh_w = max(sh_w, sname + 16)
    fe_w = max(width8(g(n)) for n in ("MSG_SH_NAME", "MSG_SH_PATH", "MSG_SH_COMMENT", "MSG_SH_USERS")) + 16 + 34 * 8 + 16
    fe_w = max(fe_w, width8(g("MSG_SH_NAME")) + 16 + 26 + 8 + width8(g("MSG_SH_GUEST")) + 16)
    bad = 0
    for name, w in (("main window", main_w), ("share editor", ed_w), ("sharing window", sh_w),
                    ("shared folder editor", fe_w)):
        if w > 640 - 8:
            print("%s: %s is %d pixels wide with topaz 8 (at most 632)" % (where, name, w))
            bad += 1
    return bad


def check(cd, cts):
    e = read_cd(cd)
    bad = check_keys(cd, {n: t for n, _, t in e})
    bad += check_layout(cd, {n: t for n, _, t in e})
    for ct in cts:
        meta, st = read_ct(ct)
        for k in ("language", "version"):
            if k not in meta:
                print("%s: missing ## %s" % (ct, k))
                bad += 1
        for name, _, text in e:
            if name not in st:
                print("%s: missing %s" % (ct, name))
                bad += 1
            elif fmts(st[name]) != fmts(text):
                print("%s: %s: formats %s, expected %s" % (ct, name, fmts(st[name]), fmts(text)))
                bad += 1
            elif ("_" in text) != ("_" in st[name]):
                print("%s: %s: shortcut marker mismatch" % (ct, name))
                bad += 1
            else:
                try:
                    st[name].encode("latin-1")
                except UnicodeEncodeError:
                    print("%s: %s: not ISO-8859-1" % (ct, name))
                    bad += 1
        bad += check_keys(ct, st)
        bad += check_layout(ct, st)
        for name in st:
            if name not in [x[0] for x in e]:
                print("%s: unknown %s" % (ct, name))
                bad += 1
    return 1 if bad else 0


def chunk(tag, data):
    pad = b"\0" if len(data) & 1 else b""
    return tag + struct.pack(">I", len(data)) + data + pad


def catalog(cd, ct, out):
    e = read_cd(cd)
    meta, st = read_ct(ct)
    body = chunk(b"FVER", meta["version"].encode("latin-1") + b"\0")
    body += chunk(b"LANG", meta["language"].encode("latin-1") + b"\0")
    body += chunk(b"CSET", b"\0" * 32)
    strs = b""
    for name, nid, _ in e:
        if name not in st or st[name] == "":
            continue
        s = st[name].encode("latin-1") + b"\0"
        strs += struct.pack(">II", nid, len(s)) + s + b"\0" * ((4 - len(s) % 4) % 4)
    body += chunk(b"STRS", strs)
    data = b"CTLG" + body
    with open(out, "wb") as f:
        f.write(b"FORM" + struct.pack(">I", len(data)) + data)


def main(a):
    if len(a) == 4 and a[1] == "header":
        header(a[2], a[3])
        return 0
    if len(a) == 5 and a[1] == "catalog":
        catalog(a[2], a[3], a[4])
        return 0
    if len(a) >= 4 and a[1] == "check":
        return check(a[2], a[3:])
    sys.stderr.write(__doc__ if __doc__ else "usage: see the header of this file\n")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
