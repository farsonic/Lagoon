#!/usr/bin/env python3
"""Generate src/core/ln_nfc_table.h: precomposed Latin letters (U+00C0..U+024F,
U+1E00..U+1EFF) that decompose canonically into base + one combining mark,
sorted by precomposed code point. Two-level decompositions (e.g. U+1EA4) are
stored as precomposed(base+mark1) + mark2, so applying the table repeatedly
composes/decomposes fully."""
import unicodedata, sys
rows = []
for cp in list(range(0xC0, 0x250)) + list(range(0x1E00, 0x1F00)):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith('<'):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) != 2:
        continue
    rows.append((cp, parts[0], parts[1]))
out = ["/* generated by tools/gen_nfc.py - do not edit */",
       "static const unsigned short ln_nfc_table[][3] = {"]
for cp, b, m in rows:
    out.append("\t{ 0x%04X, 0x%04X, 0x%04X }," % (cp, b, m))
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(len(rows), "rows")
