static const StMap *find(u32 st)
{
	int lo = 0, hi = (int)LN_ARRAY_SIZE(map) - 1;
	while (lo <= hi) {
		int m = (lo + hi) / 2;
		if (map[m].st == st)
			return &map[m];
		if (map[m].st < st)
			lo = m + 1;
		else
			hi = m - 1;
	}
	return NULL;
}

int smb_err(u32 st)
{
	const StMap *m = find(st);
	if (m)
		return m->err;
	return (st & 0xC0000000u) == 0xC0000000u ? LN_EIO : LN_OK;
}

const char *smb_status_name(u32 st)
{
	static char buf[24];
	const StMap *m = find(st);
	if (m)
		return m->name;
	ln_snprintf(buf, sizeof(buf), "NTSTATUS 0x%08x", st);
	return buf;
}
